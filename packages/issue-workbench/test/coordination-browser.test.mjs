import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtemp, rm, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { test } from 'node:test';
import { chromium } from 'playwright';
const repo = fileURLToPath(new URL('../../../', import.meta.url));

test('packed multi-source journey: save, link, reload, independent verification, failure and revocation', { timeout: 90000 }, async t => {
  const directory = await mkdtemp(join(tmpdir(), 'issue-coordination-browser-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const [pack] = JSON.parse(execFileSync(process.execPath, ['scripts/pack-publish-artifact.mjs','packages/issue-workbench', directory], { cwd: repo, encoding: 'utf8' }));
  execFileSync('tar', ['-xzf', join(directory, pack.filename), '-C', directory]);
  const { coordinationPreview, fixtureBindings } = await import(pathToFileURL(join(directory, 'package/dist/coordination-host.mjs')).href);
  let grant = true, offline = false;
  const bindings = fixtureBindings(), internalRead = bindings[1].catalog;
  bindings[1].authorize = async () => grant;
  bindings[1].catalog = async refresh => { if (refresh && offline) throw new Error('offline'); return internalRead(); };
  const server = coordinationPreview({ dataRoot: join(directory,'data'), dist: join(directory,'package/dist'), bindings });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => { server.closeAllConnections(); server.close(resolve); }));
  const url = 'http://127.0.0.1:' + server.address().port;
  assert.equal((await fetch(url + '/api/issue-coordination/state', { headers: { origin: 'https://evil.invalid' } })).status, 403);
  assert.equal((await fetch(url + '/api/issue-coordination/work', { method: 'POST', body: '{}' })).status, 403);
  const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE } : {}) }); t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(7000);
  t.after(async () => { if (t.signal.aborted) return; await mkdir('artifacts', { recursive: true }); await page.screenshot({ path: 'artifacts/coordination-last.png', fullPage: true }).catch(() => {}); });
  const errors = []; page.on('pageerror', error => { errors.push(error.message); console.error('browser:', error.message); });
  await page.goto(url);
  await page.getByText('管理来源与代码基线', { exact: true }).click();
  await page.getByLabel('默认分支', { exact: true }).first().fill('public-main');
  await page.getByRole('button', { name: '保存来源配置', exact: true }).first().click();
  await page.waitForResponse(response => response.url().endsWith('/state'));
  await page.getByText('管理来源与代码基线', { exact: true }).click();
  const queue = page.getByRole('complementary', { name: '聚合问题队列' });
  const openPublic = () => queue.getByRole('button', { name: /公开测试仓.*上游修复/ }).click();
  const openInternal = () => queue.getByRole('button', { name: /内源合成测试仓.*内部适配/ }).click();
  await openPublic();
  await page.getByLabel('本仓方案', { exact: true }).fill('通用修复方案');
  await page.getByLabel('本仓验证', { exact: true }).selectOption('passed');
  await page.getByRole('button', { name: '保存本仓记录' }).click();
  await page.getByRole('alert').filter({ hasText: '验证通过需要代码基线和验证证据' }).waitFor();
  await page.getByLabel('验证代码基线', { exact: true }).fill('upstream-abc123');
  await page.getByLabel('验证证据 / 测试结果').fill('上游测试通过');
  await page.getByLabel('本仓验证', { exact: true }).selectOption('passed');
  await page.getByRole('button', { name: '保存本仓记录' }).click();
  await page.getByRole('button', { name: '保存本仓记录' }).isDisabled();
  await page.waitForFunction(() => document.body.textContent.includes('已记录验证通过'));
  await openInternal();
  assert.equal(await page.getByLabel('本仓验证', { exact: true }).inputValue(), 'pending');
  await page.getByLabel('本仓方案', { exact: true }).fill('内部仍需移植');
  await openPublic(); await openInternal();
  assert.equal(await page.getByText('来源正文与讨论', { exact: true }).count(), 1);
  assert.equal(await page.getByLabel('本仓方案', { exact: true }).inputValue(), '内部仍需移植');
  await page.getByRole('button', { name: '更新来源', exact: true }).click();
  await page.getByRole('button', { name: '更新来源', exact: true }).waitFor();
  assert.equal(await page.getByLabel('本仓方案', { exact: true }).inputValue(), '内部仍需移植');
  await page.getByRole('button', { name: '保存本仓记录' }).click();
  await page.waitForFunction(() => document.querySelector('form button')?.textContent !== '保存中…');
  await page.getByLabel('关联问题', { exact: true }).selectOption({ label: '公开测试仓 #88 · 上游修复：重复加载问题' });
  await page.getByLabel('关系', { exact: true }).selectOption('port');
  await page.getByLabel('关联依据', { exact: true }).fill('内部旧版本仍复现');
  await page.getByLabel('共享研判结论（仅本地，不自动公开）').fill('需要适配后再测');
  await page.getByRole('button', { name: '保存关联', exact: true }).click();
  await page.getByRole('button', { name: '解除关联（保留两边记录）' }).waitFor();
  await page.reload(); await openInternal();
  assert.equal(await page.getByLabel('本仓方案', { exact: true }).inputValue(), '内部仍需移植');
  assert.equal(await page.getByLabel('本仓验证', { exact: true }).inputValue(), 'pending');
  await page.getByText('需要适配后再测', { exact: true }).waitFor();
  offline = true;
  await page.getByRole('button', { name: '更新来源', exact: true }).click();
  await page.getByText('更新失败，保留上次可读取内容', { exact: true }).waitFor();
  assert.equal(await queue.getByRole('button').count(), 3);
  await mkdir('artifacts', { recursive: true });
  await page.screenshot({ path: 'artifacts/coordination-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  assert.equal(await page.getByRole('heading', { name: '一起研判，分别验证' }).count(), 1);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: 'artifacts/coordination-mobile.png' });
  await page.getByRole('heading', { name: '本仓研判与修复记录' }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'artifacts/coordination-mobile-editor.png' });
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.screenshot({ path: 'artifacts/coordination-dark.png', fullPage: true });
  grant = false;
  await page.getByRole('button', { name: '更新来源', exact: true }).click();
  await page.getByText('来源未授权，内容不可读取', { exact: true }).waitFor();
  assert.equal(await queue.getByRole('button').count(), 1);
  assert.ok(!(await page.locator('body').textContent()).includes('需要适配后再测'));
  assert.deepEqual(errors, []);
  console.log('Coordination packed journey', pack.integrity);
});
